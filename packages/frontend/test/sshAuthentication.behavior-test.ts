import assert from 'node:assert/strict';
import { FakeWebSocket } from './support/terminal-session-runtime';
import { createWebSocketConnectionManager } from '../src/composables/useWebSocketConnection';
import { readSshAuthChallenge } from '../src/websocket/ssh-auth-challenge';

const manager = createWebSocketConnectionManager('tab1', '1', ((key: string) => key) as never);
manager.connect('ws://localhost');
const socket = FakeWebSocket.instanceList[0];
socket.open();
const challenge = { requestId: 'first', name: '', instructions: '', username: 'test', prompts: [{ prompt: 'Password:', echo: false }] };
socket.receive({ type: 'ssh:auth-prompt', payload: challenge });
assert.deepEqual(manager.authChallenge.value, challenge);
manager.respondToAuth('stale', ['no']);
assert.equal(manager.authChallenge.value?.requestId, 'first');
manager.respondToAuth('first', ['a*b']);
assert.equal(manager.authChallenge.value, null);
assert.deepEqual(JSON.parse(String(socket.sentFrameList.at(-1))), {
  type: 'ssh:auth-response', payload: { requestId: 'first', answers: ['a*b'] },
});
socket.receive({ type: 'ssh:auth-prompt', payload: { ...challenge, requestId: 'otp', prompts: [{ prompt: 'Code:', echo: false }] } });
manager.respondToAuth('otp', null);
assert.equal(manager.authChallenge.value, null);
assert.equal(socket.closeCallCount, 1);
assert.equal(manager.connectionStatus.value, 'disconnected');
assert.equal(readSshAuthChallenge({ ...challenge, prompts: [{ prompt: 'Password:', echo: 'false' }] }), null);
assert.equal(readSshAuthChallenge({ ...challenge, prompts: Array(9).fill(challenge.prompts[0]) }), null);
console.log('SSH authentication client behavior passed');

const native = createWebSocketConnectionManager('native', '2', ((key: string) => key) as never, { engine: 'openssh' });
native.connect('ws://localhost');
const nativeSocket = FakeWebSocket.instanceList.at(-1)!;
nativeSocket.open();
assert.equal(JSON.parse(String(nativeSocket.sentFrameList.at(-1))).payload.engine, 'openssh');
nativeSocket.receive({ type: 'ssh:terminal-ready', payload: { sessionId: 'native-backend', connectionId: 2 } });
assert.equal(native.isTerminalReady.value, true);
assert.equal(native.connectionStatus.value, 'terminal-ready');
assert.equal(native.statusMessage.value, 'sshAuth.nativeReady');
assert.equal(native.isConnected.value, false);
assert.equal(native.isSftpReady.value, false);
const authenticationEvent = { type: 'ssh:authenticated', payload: { sessionId: 'native-backend', connectionId: 2 } };
nativeSocket.receive({ ...authenticationEvent, payload: { ...authenticationEvent.payload, sessionId: 'stale' } });
assert.equal(native.connectionStatus.value, 'terminal-ready');
nativeSocket.receive(authenticationEvent);
assert.equal(native.connectionStatus.value, 'native-authenticated');
assert.equal(native.isConnected.value, false);
assert.equal(native.isTerminalReady.value, true);
nativeSocket.abnormalClose();
assert.equal(native.connectionStatus.value, 'disconnected');
assert.equal(native.connectionDiagnostics.value.reconnectAttempts, 0);
native.disconnect();
assert.equal(native.isTerminalReady.value, false);

import { createTerminalAuthInput } from '../src/composables/terminalAuthInput';
let transcript = '';
let submitted: string[] | null = null;
const editor = createTerminalAuthInput(text => { transcript += text; }, (_id, answers) => { submitted = answers; });
editor.start({ ...challenge, prompts: [{ prompt: 'Password:', echo: false }, { prompt: 'OTP:', echo: false }] });
editor.input('wrong\x15a*bX\x7f\r');
assert.ok(transcript.includes('OTP:'));
editor.input('123456\r');
assert.deepEqual(submitted, ['a*b', '123456']);
assert.ok(!transcript.includes('a*b') && !transcript.includes('123456'));
